"""Generate the released-tool -> family-surface map from the live registry.

Writes migration/v1_to_v2.json (one entry per tool the released 1.2.5
server registered) and docs/surface_map.md (the table the README and
CHANGELOG migration note embed). tests/unit/test_surface_map.py fails when
either checked-in file differs from a fresh generation. Same design as the
Word editor's script.

Run:  python -X utf8 scripts/generate_surface_map.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
RELEASED = ROOT / "migration" / "released_tools_1.2.5.json"
MAP = ROOT / "migration" / "v1_to_v2.json"
TABLE = ROOT / "docs" / "surface_map.md"

REMOVED = {"enable_tools", "disable_tools"}
REMOVED_REASON = "removed: every operation is available from the start"


def _registry():
    import importlib.util
    spec = importlib.util.spec_from_file_location("_gen_adapter_source",
                                                  ROOT / "scripts" / "adapter_source.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    mod.ensure_importable()
    from xlsx_mcp import license_policy
    if not license_policy.installed():
        from ks4_license_community.policy import CommunityPolicy, ProductConfig
        from xlsx_mcp import __version__
        license_policy.install(CommunityPolicy(
            ProductConfig(product_id="kitchensink4xl", display_name="KitchenSink4XL"),
            __version__))
    import xlsx_mcp.server  # noqa: F401  (registers every op)
    from xlsx_mcp import registry
    return registry


def render() -> tuple[str, dict]:
    registry = _registry()
    from xlsx_mcp.settings import Settings
    from xlsx_mcp.surface import plan
    p = plan.build(Settings())  # raises PlanError on an op with no tool
    released = json.loads(RELEASED.read_text("utf-8"))["tools"]
    tools: dict[str, dict | None] = {}
    for old in sorted(released):
        if old in REMOVED:
            tools[old] = {"tool": None, "op": None, "args_changed": None,
                          "reason": REMOVED_REASON}
            continue
        if old not in registry.REGISTRY:
            raise plan.PlanError(f"released tool {old} has no op on the family surface")
        from xlsx_mcp.ops.workflows import args_changed
        changed = args_changed(old)
        tools[old] = {"tool": p.op_tool[old], "op": old,
                      "args_changed": changed or None}
    data = {"from": "kitchensink4xl 1.2.5", "to": "kitchensink4xl 2.0",
            "call_shape": "tool(op=<op>, args={...})", "tools": tools}
    rows = ["| Released tool (1.2.5) | New tool | Op | Changed (old -> new; both work) |",
            "|---|---|---|---|"]
    for old, e in tools.items():
        if e["tool"] is None:
            rows.append(f"| `{old}` | (none) | {REMOVED_REASON} | |")
        else:
            changed = "; ".join(f"`{a}` -> `{b}`" for a, b in (e["args_changed"] or {}).items())
            rows.append(f"| `{old}` | `{e['tool']}` | `{e['op']}` | {changed} |")
    table = ("<!-- Generated by scripts/generate_surface_map.py; do not edit by hand. -->\n"
             + "\n".join(rows) + "\n")
    return table, data


def main() -> None:
    table, data = render()
    TABLE.parent.mkdir(parents=True, exist_ok=True)
    MAP.parent.mkdir(parents=True, exist_ok=True)
    TABLE.write_text(table, encoding="utf-8", newline="\n")
    MAP.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8",
                   newline="\n")
    print(f"wrote {MAP.relative_to(ROOT)} ({len(data['tools'])} entries) and "
          f"{TABLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
